def classify_difficulty(data):
    """
    Classify game difficulty for each variant based on:
      - mean final score relative to game's theoretical max
      - coefficient of variation (CV = std/mean) — high CV = harder
    """
    theoretical_max = {"breakout": 30.0, "asterix": 20.0, "freeway": 60.0}

    classification = {}
    for game in GAMES:
        tmax = theoretical_max[game]
        classification[game] = {}
        for variant in VARIANTS:
            d = data[variant][game]
            score_pct = d["mean_final"] / tmax * 100
            cv = d["std_final"] / d["mean_final"] if d["mean_final"] > 0 else float("inf")

            if score_pct >= 55 and cv < 0.5:
                level = "Easy"
            elif score_pct >= 30 or (score_pct >= 20 and cv < 0.8):
                level = "Medium"
            else:
                level = "Hard"

            classification[game][variant] = {
                "level": level,
                "score_pct": score_pct,
                "cv": cv,
            }
    return classification


