def load_results(results_root):
    data = defaultdict(dict)
    for variant in VARIANTS:
        for game in GAMES:
            pattern = os.path.join(results_root, variant, game, "*.json")
            files = glob.glob(pattern)
            if not files:
                print(f"  [WARNING] No file found: {pattern}")
                continue
            with open(files[0], "r") as f:
                raw = json.load(f)
            individuals = raw["results"]
            final_scores = [
                statistics.mean(ind["eval_trajectory"][-10:])
                for ind in individuals
            ]
            aucs = [ind["auc"] for ind in individuals]
            trajectories = [ind["eval_trajectory"] for ind in individuals]
            data[variant][game] = {
                "n": len(individuals),
                "final_scores": final_scores,
                "aucs": aucs,
                "trajectories": trajectories,
                "mean_final": statistics.mean(final_scores),
                "std_final":  statistics.stdev(final_scores) if len(final_scores) > 1 else 0,
                "median_final": statistics.median(final_scores),
                "mean_auc":   statistics.mean(aucs),
                "std_auc":    statistics.stdev(aucs) if len(aucs) > 1 else 0,
                "min_final":  min(final_scores),
                "max_final":  max(final_scores),
                "total_frames": raw.get("total_frames", "N/A"),
            }
    return data


