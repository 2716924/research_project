def check_literature_alignment(data, rankings):
    alignment = {}
    for game in GAMES:
        lit = LITERATURE[game]
        expected = lit["expected_ranking"]
        actual   = [v for v, _ in rankings[game]]

        def rank_order(lst, universe):
            return [lst.index(x) + 1 if x in lst else len(universe) + 1 for x in universe]

        exp_ranks = rank_order(expected, VARIANTS)
        act_ranks = rank_order(actual,   VARIANTS)
        n = len(VARIANTS)
        d2 = sum((r1 - r2) ** 2 for r1, r2 in zip(exp_ranks, act_ranks))
        spearman = 1 - 6 * d2 / (n * (n * n - 1)) if n > 1 else 1.0

        notes = {}
        for variant in VARIANTS:
            exp_pos = expected.index(variant) + 1 if variant in expected else n
            act_pos = next(i + 1 for i, (v, _) in enumerate(rankings[game]) if v == variant)
            direction = "higher" if act_pos < exp_pos else ("lower" if act_pos > exp_pos else "matches")
            notes[variant] = {
                "expected_rank": exp_pos,
                "actual_rank": act_pos,
                "direction": direction,
                "aligned": abs(act_pos - exp_pos) <= 1,
            }
        alignment[game] = {
            "spearman": spearman,
            "notes": notes,
        }
    return alignment


