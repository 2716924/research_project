def pairwise_vs_control(data):
    results = defaultdict(dict)
    for game in GAMES:
        ctrl_scores = data["control"][game]["final_scores"]
        for variant in VARIANTS:
            if variant == "control":
                continue
            var_scores = data[variant][game]["final_scores"]
            t, p, sig = welch_t_test(var_scores, ctrl_scores)
            diff = data[variant][game]["mean_final"] - data["control"][game]["mean_final"]
            pct  = (diff / data["control"][game]["mean_final"] * 100) if data["control"][game]["mean_final"] != 0 else 0
            results[game][variant] = {
                "t": t, "p": p, "sig": sig,
                "delta": diff, "pct": pct,
            }
    return results


