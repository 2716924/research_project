def print_table_header(headers, widths):
    top = "+" + "+".join("-" * w for w in widths) + "+"
    mid = "|" + "|".join(h.center(w) for h, w in zip(headers, widths)) + "|"
    sep = "+" + "+".join("=" * w for w in widths) + "+"
    print(top); print(mid); print(sep)

def print_table_row(cells, widths):
    print("|" + "|".join(str(c).center(w) for c, w in zip(cells, widths)) + "|")

def print_table_footer(widths):
    print("+" + "+".join("-" * w for w in widths) + "+")


