def main():
    parser = argparse.ArgumentParser(
        description="Analyse DQN variant results from MinAtar RCT experiments."
    )
    parser.add_argument(
        "--results-root", default="results",
        help="Path to the results/ directory (default: results)"
    )
    parser.add_argument(
        "--output-dir", default="analysis_output",
        help="Directory to write CSV/output files (default: analysis_output)"
    )
    args = parser.parse_args()

    print(f"\nLoading results from: {os.path.abspath(args.results_root)}")
    data = load_results(args.results_root)

    print("Computing rankings and statistics...")
    rankings   = compute_rankings(data)
    pairwise   = pairwise_vs_control(data)
    difficulty = classify_difficulty(data)
    alignment  = check_literature_alignment(data, rankings)

    print_report(data, rankings, pairwise, alignment, difficulty)

    csv_path = export_csv(data, rankings, pairwise, difficulty, args.output_dir)
    print(f"\n  Analysis complete. CSV saved to: {csv_path}\n")


if __name__ == "__main__":
    main()
