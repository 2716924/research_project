# Helper: t-test (two-sample, two-tailed, Welch's)
# ─────────────────────────────────────────────

def welch_t_test(a, b):
    """
    Compute Welch's two-sample t-statistic and approximate p-value.
    Returns (t_stat, p_value, significant_at_0.05).
    Uses an approximation for the t-distribution CDF via the incomplete
    beta function (stdlib only, no scipy dependency).
    """
    n1, n2 = len(a), len(b)
    if n1 < 2 or n2 < 2:
        return 0.0, 1.0, False

    m1, m2 = statistics.mean(a), statistics.mean(b)
    v1 = statistics.variance(a)
    v2 = statistics.variance(b)

    se = math.sqrt(v1 / n1 + v2 / n2)
    if se == 0:
        return 0.0, 1.0, False

    t = (m1 - m2) / se

    # Welch–Satterthwaite degrees of freedom
    df_num = (v1 / n1 + v2 / n2) ** 2
    df_den = (v1 / n1) ** 2 / (n1 - 1) + (v2 / n2) ** 2 / (n2 - 1)
    df = df_num / df_den if df_den > 0 else n1 + n2 - 2

    # Approximate p-value using regularised incomplete beta function
    x = df / (df + t * t)
    p = _regularised_inc_beta(df / 2, 0.5, x)
    p = max(0.0, min(1.0, p))
    return t, p, p < 0.05


def _regularised_inc_beta(a, b, x, max_iter=200, tol=1e-12):
    """Regularised incomplete beta function I_x(a,b) via continued fraction."""
    if x <= 0:
        return 0.0
    if x >= 1:
        return 1.0
    lbeta = math.lgamma(a) + math.lgamma(b) - math.lgamma(a + b)
    front = math.exp(math.log(x) * a + math.log(1 - x) * b - lbeta) / a

    def cf():
        fj = 1.0
        cj = 1.0
        dj = 1.0 - (a + b) * x / (a + 1)
        if abs(dj) < 1e-30:
            dj = 1e-30
        dj = 1.0 / dj
        fj = dj
        for m in range(1, max_iter):
            m2 = 2 * m
            num = m * (b - m) * x / ((a + m2 - 1) * (a + m2))
            dj = 1.0 + num * dj
            cj = 1.0 + num / cj
            if abs(dj) < 1e-30: dj = 1e-30
            if abs(cj) < 1e-30: cj = 1e-30
            dj = 1.0 / dj
            delta = cj * dj
            fj *= delta
            num = -(a + m) * (a + b + m) * x / ((a + m2) * (a + m2 + 1))
            dj = 1.0 + num * dj
            cj = 1.0 + num / cj
            if abs(dj) < 1e-30: dj = 1e-30
            if abs(cj) < 1e-30: cj = 1e-30
            dj = 1.0 / dj
            delta = cj * dj
            fj *= delta
            if abs(delta - 1.0) < tol:
                break
        return fj
    return front * cf()


